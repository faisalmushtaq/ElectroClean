/** An incremental SHA-256: update() with any number of byte arrays, then hex(). */
export class Sha256 {
  constructor() {
    this.h = new Int32Array([
      0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
    ]);
    this.buf = new Uint8Array(64);
    this.bufLen = 0;
    this.length = 0; // bytes seen so far
    this.done = false;
  }

  /** @param {Uint8Array} bytes */
  update(bytes) {
    if (this.done) throw new Error("SHA-256 already finished");
    let pos = 0;
    const n = bytes.length;
    this.length += n;
    if (this.bufLen > 0) {
      const take = Math.min(64 - this.bufLen, n);
      this.buf.set(bytes.subarray(0, take), this.bufLen);
      this.bufLen += take;
      pos = take;
      if (this.bufLen < 64) return this;
      compress(this.h, this.buf, 0, 1);
      this.bufLen = 0;
    }
    const whole = Math.floor((n - pos) / 64);
    if (whole > 0) {
      compress(this.h, bytes, pos, whole);
      pos += whole * 64;
    }
    if (pos < n) {
      this.buf.set(bytes.subarray(pos), 0);
      this.bufLen = n - pos;
    }
    return this;
  }

  /** @returns {Uint8Array} the 32-byte digest */
  digest() {
    if (!this.done) {
      const bitsHi = Math.floor(this.length / 0x20000000);
      const bitsLo = (this.length * 8) >>> 0;
      const pad = new Uint8Array(this.bufLen < 56 ? 64 : 128);
      pad.set(this.buf.subarray(0, this.bufLen));
      pad[this.bufLen] = 0x80;
      const end = pad.length;
      pad[end - 8] = (bitsHi >>> 24) & 0xff;
      pad[end - 7] = (bitsHi >>> 16) & 0xff;
      pad[end - 6] = (bitsHi >>> 8) & 0xff;
      pad[end - 5] = bitsHi & 0xff;
      pad[end - 4] = (bitsLo >>> 24) & 0xff;
      pad[end - 3] = (bitsLo >>> 16) & 0xff;
      pad[end - 2] = (bitsLo >>> 8) & 0xff;
      pad[end - 1] = bitsLo & 0xff;
      compress(this.h, pad, 0, pad.length / 64);
      this.done = true;
    }
    const out = new Uint8Array(32);
    for (let i = 0; i < 8; i++) {
      const v = this.h[i];
      out[4 * i] = (v >>> 24) & 0xff;
      out[4 * i + 1] = (v >>> 16) & 0xff;
      out[4 * i + 2] = (v >>> 8) & 0xff;
      out[4 * i + 3] = v & 0xff;
    }
    return out;
  }

  /** @returns {string} the digest as 64 lower-case hex digits */
  hex() {
    return toHex(this.digest());
  }
}

/** @param {Uint8Array} bytes */
export function toHex(bytes) {
  let s = "";
  for (const b of bytes) s += b.toString(16).padStart(2, "0");
  return s;
}

/** SHA-256 of bytes in memory, as hex. @param {Uint8Array} bytes */
export function sha256Hex(bytes) {
  return new Sha256().update(bytes).hex();
}

/** Bytes per read when streaming a file. */
export const READ_CHUNK_BYTES = 8 * 1024 * 1024;

/** The largest file hashed by the browser's own SHA-256 (crypto.subtle) in one piece. */
export const NATIVE_MAX_BYTES = 1024 * 1024 * 1024;

/**
 * Files up to this size are read into memory and hashed with the browser's own SHA-256
 * (crypto.subtle), which is several times faster than any JavaScript; larger files are streamed
 * through the incremental implementation above. The limit is an eighth of the device's memory as
 * the browser reports it (navigator.deviceMemory; 4 GB when it does not), at most 1 GB.
 */
export function nativeLimitBytes() {
  const gb = (typeof navigator !== "undefined" && Number(navigator.deviceMemory)) || 4;
  return Math.min(NATIVE_MAX_BYTES, Math.floor((gb * 1024 * 1024 * 1024) / 8));
}

/** True when the browser's own SHA-256 can be used here. */
export function hasNativeSha256() {
  return Boolean(globalThis.crypto && globalThis.crypto.subtle && typeof globalThis.crypto.subtle.digest === "function");
}

/**
 * SHA-256 of a Blob or File, read in pieces with Blob.slice (the next piece is read while the
 * current one is hashed). Calls onProgress(fraction) as it goes.
 * @param {Blob} blob
 * @param {{onProgress?: (fraction: number) => void, chunkBytes?: number, native?: boolean,
 *          onChunk?: (bytes: Uint8Array, offset: number) => void}} [options]
 *   onChunk sees every piece in order (used to scan a file while it is hashed).
 * @returns {Promise<string>} hex digest
 */
export async function sha256Blob(blob, options = {}) {
  const { onProgress, chunkBytes = READ_CHUNK_BYTES, onChunk } = options;
  const size = blob.size;
  const useNative = options.native !== false && !onChunk && hasNativeSha256() && size <= nativeLimitBytes();
  if (useNative) {
    try {
      // read in pieces (for the progress), then hash in one go
      const all = new Uint8Array(size);
      for (let off = 0; off < size; ) {
        const piece = new Uint8Array(await blob.slice(off, Math.min(size, off + chunkBytes)).arrayBuffer());
        if (piece.length === 0) throw new Error("The file could not be read to the end");
        all.set(piece, off);
        off += piece.length;
        if (onProgress) onProgress(0.9 * (off / size));
      }
      const digest = await globalThis.crypto.subtle.digest("SHA-256", all);
      if (onProgress) onProgress(1);
      return toHex(new Uint8Array(digest));
    } catch {
      // fall back to the streaming implementation (not enough memory, or crypto.subtle refused)
    }
  }
  const hash = new Sha256();
  let offset = 0;
  let pending = size > 0 ? blob.slice(0, Math.min(size, chunkBytes)).arrayBuffer() : null;
  while (pending) {
    const buf = await pending;
    const start = offset;
    offset += buf.byteLength;
    pending = offset < size ? blob.slice(offset, Math.min(size, offset + chunkBytes)).arrayBuffer() : null;
    const bytes = new Uint8Array(buf);
    if (bytes.length === 0) throw new Error("The file could not be read to the end");
    hash.update(bytes);
    if (onChunk) onChunk(bytes, start);
    if (onProgress) onProgress(size ? offset / size : 1);
  }
  if (onProgress && size === 0) onProgress(1);
  return hash.hex();
}
