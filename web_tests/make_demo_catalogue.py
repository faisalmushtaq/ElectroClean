"""Write electrotag/web/static/js/api/demo_catalogue.js from the Python catalogue and default settings.

    python web_tests/make_demo_catalogue.py

The demonstration has no server, so it carries its own copy of the label catalogue;
web_tests/unit/ui_catalogue.test.mjs checks that the copy still matches.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DISPLAY_KEYS = ('duration_s', 'n_channels', 'channel_colours')
sys.path.insert(0, str(REPO))

from electrotag.app.annotations.labels import default_catalogue  # noqa: E402


COMFORT_KEYS = ("break_reminder_minutes", "idle_pause_minutes", "coverage_check", "confidence")


def main() -> int:
    cat = default_catalogue()
    labels = [{"label": l.label, "value": l.value, "short_code": l.short_code, "colour": l.colour,
               "section": l.section, "is_group": l.is_group, "description": l.description} for l in cat.labels]
    settings = json.loads((REPO / "electrotag/config/default_settings.json").read_text(encoding="utf-8"))
    out = REPO / "electrotag/web/static/js/api/demo_catalogue.js"
    out.write_text(
        "// The label catalogue and default settings for the demonstration (no server).\n"
        "// Generated by web_tests/make_demo_catalogue.py from electrotag/config/artifact_labels.json\n"
        "// and default_settings.json; web_tests/unit/ui_catalogue.test.mjs checks it is up to date.\n"
        f"export const CATALOGUE = {json.dumps({'labels': labels}, ensure_ascii=False, indent=1)};\n\n"
        f"export const DEFAULT_QUICK_LABELS = {json.dumps(settings['annotation']['quick_labels'])};\n\n"
        f"export const DEFAULT_SCALINGS = {json.dumps(settings['display']['scalings'])};\n\n"
        f"export const DEFAULT_HIDE = {json.dumps(settings['channels']['hide'])};\n\n"
        f"export const DEFAULT_FILTERS = {json.dumps(settings['filters'])};\n\n"
        f"export const DEFAULT_DISPLAY = {json.dumps({k: settings['display'][k] for k in DISPLAY_KEYS})};\n\n"
        f"export const DEFAULT_LOGGING = {json.dumps(settings.get('logging', {}))};\n\n"
        "// Pauses, break reminders, the check of what has been viewed and confidence (annotation block).\n"
        f"export const DEFAULT_ANNOTATION = {json.dumps({k: settings['annotation'][k] for k in COMFORT_KEYS})};\n",
        encoding="utf-8")
    print(f"wrote {out.relative_to(REPO)} ({len(labels)} labels)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
