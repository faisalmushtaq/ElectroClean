"""Write THIRD_PARTY_NOTICES.md from the installed packages' own metadata.

Run in an environment made from ``requirements.txt``::

    python scripts/third_party_notices.py

Licences are read from each package's metadata (``License-Expression``, the
``License`` field or its licence classifiers), never typed in by hand, so the
file stays correct when versions change. The version of the Firebase JavaScript
SDK that the browser application loads is read from ``js/api/firebase.js``.
"""

from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FIREBASE_JS = REPO / "electroclean" / "web" / "static" / "js" / "api" / "firebase.js"


def requirement_names() -> list[str]:
    names = []
    for line in (REPO / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            names.append(re.split(r"[=<>!~;\[ ]", line, maxsplit=1)[0])
    return names


def licence_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [
        c.split("::")[-1].strip() for c in md.get_all("Classifier") or []
        if c.startswith("License ::") and c.strip() != "License :: OSI Approved"
    ]
    text = (md.get("License") or "").strip()
    if text and len(text) <= 80 and "\n" not in text:
        return text
    first_line = text.splitlines()[0].strip() if text else ""
    if first_line.lower().endswith("license") and len(first_line) <= 60:
        return first_line  # the field holds the whole licence text; its title names it
    if classifiers:
        return "; ".join(classifiers)
    return "see the package's licence file"


def homepage_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    for entry in md.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in ("homepage", "home", "source", "source code", "repository", "documentation"):
            return url.strip()
    return (md.get("Home-page") or "").strip()


def firebase_sdk_version() -> str:
    match = re.search(r"FIREBASE_VERSION\s*=\s*['\"]([^'\"]+)['\"]", FIREBASE_JS.read_text(encoding="utf-8"))
    return match.group(1) if match else "see js/api/firebase.js"


def main() -> int:
    rows = []
    for name in requirement_names():
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            print(f"warning: {name} is not installed; skipped", file=sys.stderr)
            continue
        rows.append((dist.metadata["Name"], dist.version, licence_of(dist), homepage_of(dist)))
    rows.sort(key=lambda r: r[0].lower())
    lines = [
        "# Third-party software",
        "",
        "ElectroClean is distributed under the PolyForm Noncommercial License 1.0.0 (see LICENSE.md). Its",
        "Python package (the ElectroClean server, the commands and the code they share with the Firebase",
        "functions) uses the following packages, each under its own licence. This list is generated by",
        "`scripts/third_party_notices.py` from the packages' own metadata for the versions in",
        "`requirements.txt`.",
        "",
        "| Package | Version | Licence | Project |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {lic} | {url} |" for n, v, lic, url in rows]
    lines += [
        "",
        "## In the browser",
        "",
        "The browser application (`electroclean/web/static`) is written for ElectroClean and needs no",
        "third-party packages; its display filters reproduce the filter designs of MNE-Python and SciPy",
        "(both under BSD licences, listed above). For a study on Firebase it loads the Firebase JavaScript",
        f"SDK, version {firebase_sdk_version()}, from Google (https://www.gstatic.com/firebasejs/), under the",
        "Apache License 2.0 (https://github.com/firebase/firebase-js-sdk).",
        "",
        "It is set in two typefaces served with it (`electroclean/web/static/fonts`, made by",
        "`scripts/make_web_fonts.py`), each under the SIL Open Font License 1.1, whose text is beside the",
        "font: Newsreader (https://github.com/productiontype/Newsreader) and JetBrains Mono",
        "(https://github.com/JetBrains/JetBrainsMono).",
        "",
    ]
    out = REPO / "THIRD_PARTY_NOTICES.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({len(rows)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
