"""Write THIRD_PARTY_NOTICES.md from the installed packages' own metadata.

Run in an environment made from ``requirements.txt``::

    python scripts/third_party_notices.py

Licences are read from each package's metadata (``License-Expression``, the
``License`` field or its licence classifiers), never typed in by hand, so the
file stays correct when versions change. The stand-alone builds also copy each
package's own licence files into ``licenses/`` (see packaging/electroclean.spec).
"""

from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def requirement_names() -> list[str]:
    names = []
    for line in (REPO / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            names.append(re.split(r"[=<>!~;\[ ]", line, maxsplit=1)[0])
    return names


def licence_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [
        c.split("::")[-1].strip() for c in md.get_all("Classifier") or []
        if c.startswith("License ::") and c.strip() != "License :: OSI Approved"
    ]
    text = (md.get("License") or "").strip()
    if text and len(text) <= 80 and "\n" not in text:
        return text
    first_line = text.splitlines()[0].strip() if text else ""
    if first_line.lower().endswith("license") and len(first_line) <= 60:
        return first_line  # the field holds the whole licence text; its title names it
    if classifiers:
        return "; ".join(classifiers)
    return "see the package's licence file"


def homepage_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    for entry in md.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        if label.strip().lower() in ("homepage", "home", "source", "source code", "repository", "documentation"):
            return url.strip()
    return (md.get("Home-page") or "").strip()


def main() -> int:
    rows = []
    for name in requirement_names():
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            print(f"warning: {name} is not installed; skipped", file=sys.stderr)
            continue
        rows.append((dist.metadata["Name"], dist.version, licence_of(dist), homepage_of(dist)))
    rows.sort(key=lambda r: r[0].lower())
    lines = [
        "# Third-party software",
        "",
        "ElectroClean is distributed under the PolyForm Noncommercial License 1.0.0 (see LICENSE.md). It",
        "uses, and the stand-alone applications include, the following packages, each under its own licence.",
        "This list is generated by `scripts/third_party_notices.py` from the packages' own metadata for the",
        "versions in `requirements.txt`; the stand-alone applications also contain each package's licence",
        "files in their `licenses` folder.",
        "",
        "| Package | Version | Licence | Project |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {lic} | {url} |" for n, v, lic, url in rows]
    lines += [
        "",
        "## Qt and Qt for Python (PySide6)",
        "",
        "The graphical interface uses Qt and Qt for Python (PySide6 and Shiboken6) under the GNU Lesser",
        "General Public License version 3; the texts of the LGPL 3.0 and of the GNU GPL 3.0 that it",
        "extends are in `licenses/LGPL-3.0.txt` and `licenses/GPL-3.0.txt`. In the stand-alone",
        "applications the Qt and PySide6 libraries are kept as separate, unmodified files in the",
        "application folder, so they can be replaced with other compatible versions. Their source code is",
        "available from the Qt Project: https://code.qt.io/cgit/pyside/pyside-setup.git/ (Qt for Python)",
        "and https://download.qt.io/official_releases/QtForPython/ (released source packages); see also",
        "https://www.qt.io/download-open-source.",
        "",
    ]
    out = REPO / "THIRD_PARTY_NOTICES.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({len(rows)} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
